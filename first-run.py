def stage_anilist_token() -> None:
    stage("AniList token")
    say(
        "Marks each episode watched at 85%. Skip it and every other script still works; "
        "only the n panel and CTRL+n go quiet."
    )

    if os.name != "nt":
        warn("the token store uses Windows CryptProtectData, so this stage is Windows-only")
        _skipped.append("AniList token: no token store outside Windows")
        return

    if not confirm("Link an AniList account now?", back=True):
        _skipped.append("AniList token: press CTRL+n in mpv when you want it")
        return

    open_url(ANILIST_AUTH)
    step("Authorize the app. AzuredBlue's public client id is already in that URL.")
    step("AniList then shows the token on the page. Copy the whole thing.")
    note("It is one long line. Nothing is echoed back but its length.")
    token = ask_secret("ANILIST_TOKEN", "Paste the token:")
    if not token:
        warn("nothing pasted")
        _skipped.append("AniList token: press CTRL+n in mpv when you want it")
        return

    note("Held in memory until the receipt is confirmed, and never shown.")
    plan("link the AniList account with the token you pasted", lambda: link_anilist(token))


def link_anilist(token: str) -> None:
    # Over stdin, never argv: the token must stay out of the process list.
    ok, lines = capture(
        [sys.executable, str(ANILIST_DIR / "anilistUpdater.py"), "--setup"],
        stdin_text=token,
    )
    # Only the script's own verdict lines get printed, so nothing can echo back.
    for line in lines:
        if line.startswith(("LINKED:", "ERROR:")):
            note(line)
    if ok:
        print(f"  {GOOD}{OK_MARK} stored{RESET} encrypted under %LOCALAPPDATA%\\mpv-anilist")
        note("Tied to this Windows account, so a copy is inert elsewhere.")
        note("AniList tokens last a year; the panel tells you when to redo this.")
    else:
        warn("AniList would not accept it")
        _skipped.append("AniList token: retry with CTRL+n in mpv")


def stage_install() -> None:
    stage("Install the config")
    say("mpv reads portable_config/ from beside its own executable.")

    home = FOUND["home"]
    if home is None:
        warn("no install folder, so there is nowhere to copy to")
        note(f"copy {CONFIG} next to your mpv.exe by hand")
        _skipped.append(f"copy {CONFIG} next to mpv.exe")
        return

    dest = home / "portable_config"
    if dest.resolve() == CONFIG.resolve():
        say(f"mpv reads {CONFIG} where it already sits, so there is nothing to copy.")
        note("Every later edit to the repo is live the next time mpv starts.")
        FOUND["installed"] = dest
        return

    say("Everything above lands in this repo first, then gets copied across.")
    say(f"from {CONFIG}")
    say(f"to   {dest}")
    if dest.exists():
        warn("that folder already exists; files with the same name get overwritten")
    plan(f"copy portable_config/ to {dest}", lambda: copy_config(dest))


def copy_config(dest: Path) -> None:
    try:
        # A stale shader cache and this machine's log are no use to a new install.
        shutil.copytree(
            CONFIG,
            dest,
            dirs_exist_ok=True,
            ignore=shutil.ignore_patterns("cache", "*.log", "__pycache__"),
        )
    except OSError as error:
        warn(f"copy failed: {error}")
        note("A folder under Program Files needs an elevated shell.")
        _skipped.append(f"copy {CONFIG} {TO} {dest}")
        return
    print(f"  {GOOD}{OK_MARK} copied{RESET} the config {TO} {dest}")
    note("Repo edits do not reach mpv until you copy again.")
    FOUND["installed"] = dest


def verify() -> None:
    """After everything is applied: how to tell it worked, and an offer to launch."""
    mpv, installed = FOUND["mpv"], FOUND["installed"]
    if mpv is None or installed is None:
        return

    # An mpv from elsewhere ignores a portable_config it is not sitting next to.
    borrowed = mpv.parent != installed.parent
    command = [str(mpv), f"--config-dir={installed}"] if borrowed else [str(mpv)]
    lines = []
    if borrowed:
        lines += [
            f"{mpv} lives elsewhere, so it needs the config pointed out to it:",
            f'{MUTED}mpv --config-dir="{installed}"{RESET}',
            "",
        ]
    lines += [
        "Open any video, then:",
        f"{keycap('F6')}  the keyboard map. Every key drawn means input.conf loaded.",
        f"{keycap('Tab')}  the uosc interface. A timeline means uosc loaded and patched.",
        f"{keycap('F4')}  the subtitle index. Needs ffmpeg and a subtitle track.",
        "",
        f"{MUTED}mpv writes its log to {installed / 'mpv.log'} if something is missing.{RESET}",
    ]
    card("Verify", lines, icon="done")
    if confirm("Launch mpv now to try it?"):
        try:
            subprocess.Popen(command, cwd=str(mpv.parent))
        except OSError as error:
            warn(f"could not launch mpv: {error}")


def main() -> None:
    banner("moonlight-mpv first run")
    run_stages(
        [
            stage_prerequisites,
            stage_uosc,
            stage_patch,
            stage_shaders,
            stage_layout,
            stage_anilist_deps,
            stage_anilist_token,
            stage_install,
            receipt,
        ]
    )
    if _approved:
        apply()
        verify()
    else:
        note("nothing was changed")
    finish()


if __name__ == "__main__":
    run(main)

