def https_request(url: str, accept: str = "*/*") -> urllib.request.Request:
    """Build a request, refusing any scheme but https.

    Download URLs arrive from a GitHub API response rather than from this file,
    so the scheme is checked here instead of trusted.
    """
    if not url.startswith("https://"):
        raise ValueError(f"refusing a URL that is not https: {url}")
    return urllib.request.Request(  # noqa: S310  the scheme is enforced above
        url,
        headers={"User-Agent": "moonlight-mpv-first-run", "Accept": accept},
    )


def fetch_json(url: str) -> dict:
    request = https_request(url, "application/vnd.github+json")
    with urllib.request.urlopen(request, timeout=20) as response:  # noqa: S310  scheme checked above
        return json.load(response)


def latest_release(repo: str) -> tuple[str, list[tuple[str, str]]]:
    """Tag, then the name and download URL of every asset on it.

    Names are read off the release rather than guessed, since they carry a
    version, a build date and a commit hash that nothing here could reconstruct.
    """
    try:
        payload = fetch_json(f"https://api.github.com/repos/{repo}/releases/latest")
    except (urllib.error.URLError, OSError, ValueError) as error:
        warn(f"could not reach the GitHub API for {repo}: {error}")
        return "", []
    return payload.get("tag_name", ""), [
        (asset["name"], asset["browser_download_url"])
        for asset in payload.get("assets", [])
        if asset.get("name") and asset.get("browser_download_url")
    ]


def latest_assets(repo: str) -> list[tuple[str, str]]:
    return latest_release(repo)[1]


def pick_build(assets: list[tuple[str, str]]) -> tuple[str, str] | None:
    """The one build on a release that fits the machine running this.

    These releases carry a dozen archives: three architectures, each with a
    debug and a headers-only variant, plus ffmpeg on its own. Only one of them
    is the player for this CPU, so the human is never asked to tell them apart.
    """
    arch = ARCHES.get(platform.machine(), "")
    if not arch:
        warn(f"no build matches {platform.machine()}")
        return None

    fitting = [
        (name, url)
        for name, url in assets
        if name.lower().startswith("mpv-")
        and f"-{arch}-" in name
        and not any(skip in name for skip in ("-dev-", "-debug-", "-lgpl-"))
    ]
    # A -v3 build needs AVX2, which a CPU older than roughly 2014 lacks, so the
    # plain one is the only safe automatic pick.
    fitting.sort(key=lambda asset: ("-v3-" in asset[0], asset[0]))
    return fitting[0] if fitting else None


def unpack(archive: Path, dest: Path) -> bool:
    if archive.suffix.lower() == ".zip":
        try:
            with zipfile.ZipFile(archive) as zipped:
                zipped.extractall(dest)
        except (zipfile.BadZipFile, OSError) as error:
            warn(f"could not unpack {archive.name}: {error}")
            return False
        return True
    return unpack_7z(archive, dest)


def unpack_7z(archive: Path, dest: Path) -> bool:
    """Unpack a .7z with whatever the machine already has.

    Windows ships bsdtar, whose libarchive reads 7-Zip, so nothing has to be
    installed. It is addressed by full path on purpose: a `tar` earlier in PATH
    is usually GNU tar, which cannot read the format and fails confusingly.
    """
    attempts = []
    bsdtar = Path(os.environ.get("SYSTEMROOT", r"C:\Windows")) / "System32" / "tar.exe"
    if bsdtar.is_file():
        attempts.append([str(bsdtar), "-xf", str(archive), "-C", str(dest)])
    for exe in ("7z", "7za", "7zz"):
        found = have(exe)
        if found:
            attempts.append([found, "x", f"-o{dest}", "-y", str(archive)])

    for command in attempts:
        ok, output = capture(command)
        if ok:
            return True
        note(f"{Path(command[0]).name} could not read it: {' '.join(output[-1:])}")

    warn("nothing on this machine can unpack a .7z")
    note("Windows 10 and later ship one at System32\\tar.exe; otherwise install 7-Zip.")
    return False


def download(url: str, dest: Path) -> bool:
    say(f"downloading {dest.name}")
    try:
        request = https_request(url)
        with urllib.request.urlopen(request, timeout=60) as response, dest.open("wb") as out:  # noqa: S310  scheme checked in https_request
            shutil.copyfileobj(response, out)
    except (urllib.error.URLError, OSError, ValueError) as error:
        warn(f"download failed: {error}")
        dest.unlink(missing_ok=True)
        return False
    return True


def zip_members_under(archive: zipfile.ZipFile, marker: str) -> list[str]:
    """Members sitting under `marker`, wherever the archive roots that folder."""
    marker = marker.strip("/") + "/"
    return [name for name in archive.namelist() if marker in name.replace("\\", "/")]


def extract_subtree(zip_path: Path, marker: str, dest: Path) -> bool:
    """Copy one subtree out of a zip into dest, flattening the archive's prefix."""
    try:
        with zipfile.ZipFile(zip_path) as archive:
            members = zip_members_under(archive, marker)
            if not members:
                warn(f"{zip_path.name} has no {marker}/ inside it")
                note("top level of the archive: " + ", ".join(sorted(
                    {name.replace("\\", "/").split("/")[0] for name in archive.namelist()}
                )))
                return False
            marker_slash = marker.strip("/") + "/"
            for name in members:
                clean = name.replace("\\", "/")
                relative = clean.split(marker_slash, 1)[1]
                if not relative or clean.endswith("/"):
                    continue
                target = dest / relative
                target.parent.mkdir(parents=True, exist_ok=True)
                with archive.open(name) as source, target.open("wb") as out:
                    shutil.copyfileobj(source, out)
    except (zipfile.BadZipFile, OSError) as error:
        warn(f"could not read {zip_path}: {error}")
        return False
    return True


def extract_pattern(zip_path: Path, suffixes: tuple[str, ...], dest: Path) -> int:
    """Extract every file with one of these suffixes, flat, into dest."""
    count = 0
    try:
        with zipfile.ZipFile(zip_path) as archive:
            dest.mkdir(parents=True, exist_ok=True)
            for name in archive.namelist():
                if name.endswith("/") or not name.lower().endswith(suffixes):
                    continue
                target = dest / Path(name.replace("\\", "/")).name
                with archive.open(name) as source, target.open("wb") as out:
                    shutil.copyfileobj(source, out)
                count += 1
    except (zipfile.BadZipFile, OSError) as error:
        warn(f"could not read {zip_path}: {error}")
        return 0
    return count


def referenced_shaders() -> set[str]:
    """Every shader path input.conf and profiles.conf actually load."""
    found: set[str] = set()
    for name in ("input.conf", "profiles.conf", "mpv.conf"):
        path = CONFIG / name
        if not path.is_file():
            continue
        for line in path.read_text(encoding="utf-8", errors="replace").splitlines():
            if line.lstrip().startswith("#"):  # commented-out bindings load nothing
                continue
            found.update(SHADER_REF.findall(line))
    return found


def set_conf_option(path: Path, key: str, value: str) -> None:
    """Upsert `key=value` in an mpv script-opts file, leaving comments alone."""
    lines = path.read_text(encoding="utf-8").splitlines() if path.is_file() else []
    pattern = re.compile(rf"^\s*{re.escape(key)}\s*=")
    replaced = False
    for index, line in enumerate(lines):
        if pattern.match(line):
            lines[index] = f"{key}={value}"
            replaced = True
    if not replaced:
        lines.append(f"{key}={value}")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"  {GOOD}{OK_MARK} set{RESET} {key}={value} {TO} {path.name}")


def find_mpv() -> Path | None:
    on_path = have("mpv")
    if on_path:
        return Path(on_path)
    # The build SVP ships is where this config grew up, so it is worth a look.
    for candidate in (
        Path(os.environ.get("PROGRAMFILES(X86)", r"C:\Program Files (x86)"))
        / "SVP 4" / "mpv64" / "mpv.exe",
        Path(os.environ.get("PROGRAMFILES", r"C:\Program Files")) / "mpv" / "mpv.exe",
    ):
        if candidate.is_file():
            return candidate
    return None


def current_layout() -> str:
    if not LAYOUT_CONF.is_file():
        return ""
    for line in LAYOUT_CONF.read_text(encoding="utf-8").splitlines():
        found = re.match(r"^\s*layout\s*=\s*(\S+)", line)
        if found:
            return found.group(1)
    return ""


def release_zip(repo: str, hint: str) -> tuple[str, str, str] | None:
    """Tag, name and URL of the one zip on a repo's latest release, or None."""
    tag, assets = latest_release(repo)
    zips = [
        (name, url)
        for name, url in assets
        if name.lower().endswith(".zip") and hint.lower() in name.lower()
    ]
    if not zips:
        return None
    return tag, zips[0][0], zips[0][1]


def find_build() -> tuple[str, str, str] | None:
    """Repo, asset name and URL of the build for this machine.

    The sources are tried in the order mpv.io lists them, so a release that is
    mid-upload or missing an architecture falls through to the next rather than
    dead-ending the wizard.
    """
    for _, repo in MPV_BUILDS:
        picked = pick_build(latest_assets(repo))
        if picked:
            return repo, picked[0], picked[1]
    return None


